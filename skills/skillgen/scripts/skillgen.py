# github repos
# --------------------------------------------------------------------------


def do_repo(args: argparse.Namespace, ret: Retention) -> OrderedDict[str, str]:
    """Shallow-clone and harvest markdown. Cloning beats the API: no token,
    no rate limit, no pagination, and it is what git is for."""
    refs: OrderedDict[str, str] = OrderedDict()
    tmp = Path(tempfile.mkdtemp(prefix="skillgen-"))
    try:
        url = args.repo if "://" in args.repo else f"https://github.com/{args.repo}.git"
        clone = subprocess.run(
            ["git", "clone", "--depth", "1", "--quiet", url, str(tmp / "r")],
            capture_output=True,
            text=True,
            check=False,
        )
        if clone.returncode != 0:
            sys.exit(f"clone failed: {clone.stderr.strip()}")

        repo = tmp / "r"
        files = sorted(p for p in repo.rglob("*.md") if ".git" not in p.parts)
        files += sorted(p for p in repo.rglob("*.mdx") if ".git" not in p.parts)
        if not files:
            sys.exit("no markdown found in repo")

        for f in files[: args.max_pages]:
            text = f.read_text(errors="replace")
            if words(text) < MIN_WORDS_PER_DOC:
                continue  # changelog stubs, badge-only readmes
            rel = f.relative_to(repo)
            body = f"# {rel}\n\n{text}"
            refs[f"{slug(str(rel.with_suffix('')))}.md"] = body
            ret.add(str(rel)[:34], words(text), words(body))
            print(f"  ok {rel} ({words(text):,} words)")
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    return refs


