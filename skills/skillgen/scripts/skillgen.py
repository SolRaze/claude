# pdf
# --------------------------------------------------------------------------


def do_pdf(args: argparse.Namespace, ret: Retention) -> OrderedDict[str, str]:
    from pypdf import PdfReader

    path = Path(args.path).expanduser()
    if not path.exists():
        sys.exit(f"no such file: {path}")

    reader = PdfReader(str(path))
    chunks = [(i, (pg.extract_text() or "").strip()) for i, pg in enumerate(reader.pages, 1)]
    text = "\n\n".join(t for _, t in chunks if t)
    empty = [i for i, t in chunks if not t]

    if not text.strip():
        sys.exit(
            f"extracted no text from {path.name}. Likely a scanned PDF -- "
            "pypdf cannot read images. OCR it first (e.g. ocrmypdf)."
        )
    if empty:
        print(f"  !! {len(empty)}/{len(chunks)} pages yielded no text (scanned?): {empty[:10]}")

    name = slug(path.stem)
    body = f"# {path.name}\n\n{text}"
    ret.add(path.name[:34], words(text), words(body))
    print(f"  ok {name}.md ({words(text):,} words, {len(chunks)} pages)")
    return OrderedDict({f"{name}.md": body})


# --------------------------------------------------------------------------

HANDLERS = {"man": do_man, "web": do_web, "repo": do_repo, "pdf": do_pdf}


def main() -> None:
    p = argparse.ArgumentParser(
        prog="skillgen", description="Turn documentation into Claude skills, losslessly."
    )
    # Shared so the flags work after the subcommand too: `skillgen man tmux --name x`
    # is the order everyone actually types.
    common = argparse.ArgumentParser(add_help=False)
    common.add_argument("--name", help="skill name (default: derived from source)")
    common.add_argument("--description", default="", help="SKILL.md frontmatter description")
    common.add_argument("--force", action="store_true", help="write even if retention check fails")
    common.add_argument("--dry-run", action="store_true", help="extract and check, write nothing")
    sub = p.add_subparsers(dest="cmd", required=True)

    # Explicit subcommands, not auto-detection. The tool this replaces guessed
    # source type from the path and silently routed a man-page directory to its
    # codebase analyser, producing an empty skill. Guessing was the bug.
    m = sub.add_parser("man", help="man pages", parents=[common])
    m.add_argument("pages", nargs="+")

    w = sub.add_parser("web", help="documentation website", parents=[common])
    w.add_argument("url")
    w.add_argument("--prefix", help="only crawl URLs under this prefix (default: the start URL)")
    w.add_argument("--max-pages", type=int, default=100)
    w.add_argument("--delay", type=float, default=0.5, help="seconds between requests")

    r = sub.add_parser("repo", help="github repo markdown", parents=[common])
    r.add_argument("repo", help="owner/repo or clone URL")
    r.add_argument("--max-pages", type=int, default=200)

    d = sub.add_parser("pdf", help="pdf document", parents=[common])
    d.add_argument("path")

    args = p.parse_args()

    default_name = {
        "man": lambda: slug(args.pages[0]) if args.cmd == "man" else "",
        "web": lambda: slug(urlparse(args.url).netloc.split(".")[0]) if args.cmd == "web" else "",
        "repo": lambda: slug(args.repo.rstrip("/").split("/")[-1].removesuffix(".git"))
        if args.cmd == "repo"
        else "",
        "pdf": lambda: slug(Path(args.path).stem) if args.cmd == "pdf" else "",
    }[args.cmd]
    name = args.name or default_name()

    print(f"==> {args.cmd}: building skill '{name}'")
    ret = Retention()
    refs = HANDLERS[args.cmd](args, ret)

    if not refs:
        sys.exit("nothing extracted; no skill written")

    passed = ret.report(WEB_RETENTION_FLOOR if args.cmd == "web" else RETENTION_FLOOR)
    total = sum(words(b) for b in refs.values())
    print(f"\n  {len(refs)} reference(s), {total:,} words")

    if not passed and not args.force:
        sys.exit("\nFAILED retention check. Nothing written. Investigate, or re-run with --force.")
    if args.dry_run:
        print("\ndry run; nothing written")
        return

    desc = args.description or f"Reference documentation for {name}, generated from source."
    root = write_skill(name, desc, refs)
    print(f"\nwrote {root}")


if __name__ == "__main__":
    main()
