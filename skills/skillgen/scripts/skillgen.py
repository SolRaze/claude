# man pages
# --------------------------------------------------------------------------


def render_man(page: str) -> str:
    """man + col -b. col strips the backspace-overstrike bold/underline that
    man emits for terminals; without it every word arrives doubled."""
    man = subprocess.run(["man", page], capture_output=True, text=True, check=False)
    if man.returncode != 0 or not man.stdout.strip():
        return ""
    col = subprocess.run(["col", "-b"], input=man.stdout, capture_output=True, text=True, check=False)
    return col.stdout


def do_man(args: argparse.Namespace, ret: Retention) -> OrderedDict[str, str]:
    refs: OrderedDict[str, str] = OrderedDict()
    for page in args.pages:
        text = render_man(page)
        if not text.strip():
            print(f"  !! no man page for '{page}'", file=sys.stderr)
            ret.add(page, 0, 0)
            continue
        body = f"# {page}\n\n{text}"
        refs[f"{slug(page)}.md"] = body
        # Source and output are the same bytes, so this asserts the pipeline
        # rather than the parser -- it catches a broken col/man, not much else.
        ret.add(page, words(text), words(body))
    return refs


# --------------------------------------------------------------------------
# web docs
# --------------------------------------------------------------------------

_STRIP = ["script", "style", "nav", "footer", "header", "aside", "noscript", "form"]
_MAIN = ["main", "article", '[role="main"]', ".markdown-body", ".content", "#content", ".doc"]


def extract_html(html: str):
    """Return (markdown, body_words).

    Container choice is by text volume, never by selector order. First-match
    ordering is a trap: on Asciidoctor pages `.content` is an 18-word
    decorative div while `#content` holds the whole document, so an ordered
    list silently yields an empty skill. Pick the richest candidate instead,
    and only prefer it over <body> when it retains most of the text -- that
    keeps real containers (which drop nav chrome) while refusing a container
    that would throw the document away.

    Retention is reported against <body>, not against the chosen node, so a
    bad container choice surfaces as a low ratio rather than a perfect score
    on a tiny fragment.
    """
    from bs4 import BeautifulSoup
    from markdownify import markdownify

    soup = BeautifulSoup(html, "html.parser")
    for tag in soup(_STRIP):
        tag.decompose()

    if soup.body is None:
        return "", 0
    body_words = words(soup.body.get_text(" "))

    candidates = [n for n in (soup.select_one(sel) for sel in _MAIN) if n]
    node = soup.body
    if candidates:
        best = max(candidates, key=lambda n: words(n.get_text(" ")))
        if words(best.get_text(" ")) >= 0.5 * body_words:
            node = best

    md = markdownify(str(node), heading_style="ATX", code_language="").strip()
    md = re.sub(r"\n{3,}", "\n\n", md)
    return md, body_words


def do_web(args: argparse.Namespace, ret: Retention) -> OrderedDict[str, str]:
    import httpx

    start = args.url.rstrip("/")
    origin = urlparse(start).netloc
    prefix = args.prefix or start

    seen: set[str] = set()
    queue = [start]
    refs: OrderedDict[str, str] = OrderedDict()

    # A real UA: some doc hosts 403 the default, which would otherwise look
    # like an extraction bug rather than a network one.
    headers = {"User-Agent": "skillgen (+local docs-to-skill tool)"}
    with httpx.Client(follow_redirects=True, timeout=30, headers=headers) as client:
        while queue and len(refs) < args.max_pages:
            url = queue.pop(0)
            if url in seen:
                continue
            seen.add(url)
            try:
                r = client.get(url)
                r.raise_for_status()
            except (httpx.HTTPError, httpx.InvalidURL) as exc:
                print(f"  !! {url}: {exc}", file=sys.stderr)
                continue
            if "html" not in r.headers.get("content-type", ""):
                continue

            md, src_words = extract_html(r.text)
            path = urlparse(url).path.strip("/") or "index"
            name = f"{slug(path)}.md"
            if md and words(md) >= MIN_WORDS_PER_DOC:
                refs[name] = f"# {path}\n\nSource: {url}\n\n{md}"
                ret.add(path[:34] or "index", src_words, words(refs[name]))
                print(f"  ok {name} ({words(md):,} words)")

            from bs4 import BeautifulSoup

            for a in BeautifulSoup(r.text, "html.parser").find_all("a", href=True):
                nxt = urljoin(url, a["href"]).split("#")[0]
                if urlparse(nxt).netloc == origin and nxt.startswith(prefix) and nxt not in seen:
                    queue.append(nxt)

            time.sleep(args.delay)  # politeness; these are volunteer-run doc hosts
    return refs


