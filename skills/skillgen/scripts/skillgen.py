"""Turn documentation into Claude skills, losslessly or not at all.

Sources: man pages, documentation websites, GitHub repos, PDFs.

Design note: the upstream tool this replaces reported "skill built" while
silently discarding 96% of its input. Every extractor here therefore
measures input words against output words and refuses to write a skill that
fails the retention floor. A loud failure is the product.
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
import time
from collections import OrderedDict
from pathlib import Path
from urllib.parse import urljoin, urlparse

SKILLS_DIR = Path.home() / ".claude" / "skills"

# A page yielding less than this is almost certainly an extraction failure
# (nav-only shell, scanned PDF page, stub man page) rather than a short doc.
MIN_WORDS_PER_DOC = 50
# Fraction of source words that must survive extraction. man/repo/pdf are
# verbatim copies, so anything under 90% means the pipeline ate something.
RETENTION_FLOOR = 0.90
# Web is measured against <body>, where dropping nav/sidebar/footer chrome is
# correct behaviour, so the floor only has to catch container-choice disasters.
WEB_RETENTION_FLOOR = 0.50


def words(text: str) -> int:
    return len(text.split())


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


class Retention:
    """Tracks input vs output words so silent content loss cannot happen."""

    def __init__(self) -> None:
        self.rows: list[tuple[str, int, int]] = []

    def add(self, label: str, src_words: int, out_words: int) -> None:
        self.rows.append((label, src_words, out_words))

    def report(self, floor: float) -> bool:
        print("\n  retention:")
        ok = True
        for label, src, out in self.rows:
            # src==0 means the source itself was empty; ratio is meaningless.
            ratio = (out / src) if src else 1.0
            flag = "ok "
            if out < MIN_WORDS_PER_DOC:
                flag, ok = "EMPTY", False
            elif ratio < floor:
                flag, ok = "LOSSY", False
            print(f"    {flag:5} {label:<34} {src:>7} -> {out:>7} ({ratio:6.1%})")
        return ok


def write_skill(name: str, description: str, refs: OrderedDict[str, str], notes: str = "") -> Path:
    """Write SKILL.md + references/. SKILL.md stays an index: it is always in
    context, while references are read only on demand."""
    root = SKILLS_DIR / name
    (root / "references").mkdir(parents=True, exist_ok=True)

    for filename, body in refs.items():
        (root / "references" / filename).write_text(body)

    index = "\n".join(
        f"- `references/{fn}` - {words(body):,} words" for fn, body in refs.items()
    )
    total = sum(words(b) for b in refs.values())
    guidance = (
        "\nThese are large. Grep for the term you need; do not read a whole file.\n"
        if total > 20000
        else ""
    )
    (root / "SKILL.md").write_text(
        f"---\nname: {name}\ndescription: {description}\n---\n\n"
        f"# {name}\n\n"
        f"Generated by skillgen from source documentation. {total:,} words.\n\n"
        f"## References\n\n{index}\n{guidance}"
        + (f"\n## Notes\n\n{notes}\n" if notes else "")
    )
    return root


